// Throwaway tooling spike for docs/vtt/design/shared-v1-schemas-proposal.md
// ("run a small proof using the chosen pinned tools"). The schemas here are
// NOT the canonical contract; Codex owns contracts/vtt/v1/. This only proves
// that the pinned generator tools behave as the proposal assumes:
//   1. closed tagged unions and local cross-file $ref compile in both tools;
//   2. an empty completion patch validates;
//   3. a GM-private field in a table payload is rejected;
//   4. generated output is byte-identical across runs (determinism);
//   5. the generated table validator does not contain the GM schema;
//   6. TypeScript narrows on the discriminants (checked by tsc separately).
//
// Usage (from frontend/vtt): node spike/protocol/run.mjs

import { mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { compile } from 'json-schema-to-typescript';

const here = resolve(import.meta.dirname);
const schemasDir = join(here, 'schemas');
const outDir = join(here, 'out');
const load = (name) => JSON.parse(readFileSync(join(schemasDir, `${name}.schema.json`), 'utf-8'));

const AJV_OPTIONS = {
  strict: true,
  allErrors: false,
  coerceTypes: false,
  useDefaults: false,
  removeAdditional: false,
  ownProperties: true,
  code: { source: true, esm: true, lines: true },
};

function ajvFor(surface) {
  const ajv = new Ajv(AJV_OPTIONS);
  ajv.addSchema(load('common'));
  ajv.addSchema(load('table')); // GM patches reference table's EntityRef
  if (surface === 'gm') ajv.addSchema(load('gm'));
  return ajv;
}

// Ajv 8.20.0 emits require() for runtime helpers even with code.esm. Rewrite
// exactly the helpers we allow to an ESM shim; any other require() is an
// error, so a new helper cannot slip into a browser bundle unnoticed.
const RUNTIME_HELPERS = { ucs2length: 'ucs2length' };
function rewriteRuntime(code) {
  const imports = new Set();
  const out = code.replace(
    /const (\w+) = require\("ajv\/dist\/runtime\/(\w+)"\)\.default;/g,
    (_m, local, helper) => {
      const exported = RUNTIME_HELPERS[helper];
      if (!exported) throw new Error(`unsupported Ajv runtime helper: ${helper}`);
      imports.add(`import { ${exported} as ${local} } from './ajv-runtime.mjs';`);
      return '';
    },
  );
  if (/\brequire\(/.test(out)) throw new Error('generated validator still contains require()');
  return `${[...imports].sort().join('\n')}\n${out}`;
}

async function generate() {
  const files = {};
  for (const surface of ['table', 'gm']) {
    const ajv = ajvFor(surface);
    const id = `https://vtt.invalid/v1/${surface}.schema.json`;
    files[`${surface}.validators.mjs`] = rewriteRuntime(
      standaloneCode(ajv, { [`validate${surface === 'gm' ? 'Gm' : 'Table'}Frame`]: id }),
    );
    files[`${surface}.d.ts`] = await compile(load(surface), surface === 'gm' ? 'GmFrame' : 'TableFrame', {
      cwd: schemasDir,
      bannerComment: '/* Generated by spike/protocol/run.mjs. Do not edit. */',
      unknownAny: true,
      additionalProperties: false,
      strictIndexSignatures: true,
      declareExternallyReferenced: true,
      format: true,
    });
  }
  return files;
}

const digest = (files) =>
  createHash('sha256')
    .update(Object.keys(files).sort().map((k) => `${k}\n${files[k]}`).join('\n'))
    .digest('hex');

const results = [];
const check = (name, ok, detail = '') => {
  results.push({ name, ok, detail });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? `  (${detail})` : ''}`);
};

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const first = await generate();
const second = await generate();
check('generation is deterministic across runs', digest(first) === digest(second), digest(first).slice(0, 16));
for (const [name, text] of Object.entries(first)) writeFileSync(join(outDir, name), text);
writeFileSync(join(outDir, 'ajv-runtime.mjs'), readFileSync(join(here, 'ajv-runtime.mjs')));

const { ucs2length: shim } = await import(pathToFileURL(join(here, 'ajv-runtime.mjs')).href);
const ajvUcs2 = (await import('ajv/dist/runtime/ucs2length.js')).default.default;
const samples = ['', 'a', 'Valeros', 'é', 'é', '\u{1F409}', 'a\u{1F409}b', '\ud800', '\udc00', '\ud800\ud800', 'x\udbffy', '\u{10FFFF}'];
check('ESM ucs2length matches Ajv on every edge case', samples.every((s) => shim(s) === ajvUcs2(s)));

// Runtime helper imports: they must be ESM imports a bundler can follow,
// never a runtime schema compile.
const tableCode = first['table.validators.mjs'];
check('standalone output uses ESM imports, no require()', !/\brequire\(/.test(tableCode));
check('standalone output never compiles at runtime', !/new Function|\beval\(/.test(tableCode));
check('table validator does not embed the GM schema', !tableCode.includes('gm.schema.json') && !tableCode.includes('"hp"'));

const validators = {
  table: (await import(pathToFileURL(join(outDir, 'table.validators.mjs')).href)).validateTableFrame,
  gm: (await import(pathToFileURL(join(outDir, 'gm.validators.mjs')).href)).validateGmFrame,
};
const cases = JSON.parse(readFileSync(join(here, 'fixtures', 'cases.json'), 'utf-8'));
for (const c of cases) {
  const got = validators[c.schema](c.message) === true;
  check(`fixture: ${c.name}`, got === c.valid, `expected ${c.valid ? 'valid' : 'invalid'}`);
}

// Values JSON text cannot carry but a decoded message can (JSON.parse of 1e400
// yields Infinity). The proposal requires finite numbers.
const inf = { ...cases[0].message, entities: [{ ...cases[0].message.entities[0], x: Infinity }] };
check('Infinity coordinate is rejected', validators.table(inf) === false);
const nan = { ...cases[0].message, entities: [{ ...cases[0].message.entities[0], x: NaN }] };
check('NaN coordinate is rejected', validators.table(nan) === false);
const proto = JSON.parse(`{"schemaVersion":1,"frame":"patch","subscriptionId":"subAAAAAAAAAAAAAAAA","seq":1,"upserted":[],"removed":[],"__proto__":{"x":1}}`);
check('own "__proto__" key is rejected as an extra property', validators.table(proto) === false);

writeFileSync(
  join(outDir, 'narrowing.ts'),
  `import type { TableFrame } from './table';
export function seqOf(frame: TableFrame): number {
  if (frame.frame === 'snapshot') {
    const zero: 0 = frame.seq; // narrowed to the snapshot variant
    return zero + frame.entities.length;
  }
  // narrowed to the patch variant
  return frame.seq + frame.upserted.length + frame.removed.length;
}
export function labelOf(frame: TableFrame): string {
  const first = frame.frame === 'snapshot' ? frame.entities[0] : frame.upserted[0];
  if (first && first.kind === 'token') return first.label; // narrowed by kind
  return '';
}
`,
);

const failed = results.filter((r) => !r.ok).length;
console.log(`\n${results.length - failed}/${results.length} checks passed. Types written to ${outDir}; run tsc on narrowing.ts next.`);
process.exit(failed ? 1 : 0);
