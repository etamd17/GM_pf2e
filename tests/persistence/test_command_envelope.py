def test_check_envelope_accepts_every_valid_shape():
    envelope = body(
        expected=[{"kind": "character.play", "id": "c7", "rev": 0},
                  {"kind": "prompt", "id": "p1", "status": "open"},
                  {"kind": "prompt", "id": "p2", "status": "open"}],
        payload={"targets": ["t1", "t2"], "recipient": None, "amount": 7.0, "note": [1, 2]})
    checked = check_envelope(envelope, TOKEN, route_campaign_id=CID)
    assert isinstance(checked, CheckedEnvelope)
    assert (checked.principal, checked.principal_kind, checked.principal_id) == (
        TOKEN, "integration_token", "cred-1")
    assert checked.digest == command_digest(envelope | {"override": None})
    for payload in ({"targets": "t1"}, {"targets": []}, {}):
        check_envelope(body(payload=payload), USER, route_campaign_id=CID)
    check_envelope(body(type=PUBLISH, expected=[{"kind": "character.build", "id": "c7",
                                                 "rev": 3}]), USER, route_campaign_id=CID)


def test_checked_envelope_is_a_read_only_detached_copy_of_known_keys():
    envelope = body(extra={"x": 1})
    checked = check_envelope(envelope, USER, route_campaign_id=CID)
    envelope["payload"]["amount"] = 99
    envelope["subject"]["character_id"] = "other"
    assert checked.envelope["payload"]["amount"] == 7
    assert checked.envelope["subject"] == {"character_id": "c7"}
    assert "extra" not in checked.envelope and checked.envelope["override"] is None
    with pytest.raises(TypeError):
        checked.envelope["type"] = "x"
    with pytest.raises(dataclasses.FrozenInstanceError):
        checked.digest = "x"


