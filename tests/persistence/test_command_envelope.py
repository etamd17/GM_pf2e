def body(**changes):
    envelope = {
        "schema": 1, "operation_id": "op-3f9c2e7a1b5d4c60", "campaign_id": CID, "epoch": 1,
        "type": DAMAGE, "subject": {"character_id": "c7"}, "expected": [],
        "rules": {"profile": "dnd5e-2024"}, "payload": {"amount": 7, "damage_type": "fire"},
        "client": {"origin": "website"},
    }
    for key, value in changes.items():
        if value is _DROP:
            envelope.pop(key, None)
        else:
            envelope[key] = value
    return envelope


_DROP = object()


def refused(envelope, principal=USER, *, route=CID):
    with pytest.raises(EnvelopeRefusal) as caught:
        check_envelope(envelope, principal, route_campaign_id=route)
    return caught.value.code, caught.value.http_status


