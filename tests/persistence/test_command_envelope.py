def test_override_changes_the_digest_and_absent_equals_null():
    def digest(**changes):
        return check_envelope(body(**changes), USER, route_campaign_id=CID).digest
    absent = digest()
    assert digest(override=None) == absent
    added = digest(override={"reason": "late"})
    assert added != absent and digest(override={"reason": "later"}) != added


def test_integral_floats_hash_as_ints_everywhere():
    assert command_digest(_digest_body(schema=1.0, payload={"amount": [7.0, (2.0,)]})) == \
        command_digest(_digest_body(payload={"amount": [7, [2]]}))
    assert command_digest(_digest_body(payload={"amount": 7.5})) != command_digest(_digest_body())


